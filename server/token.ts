import { createHmac, randomBytes, timingSafeEqual } from "node:crypto";
import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

// One secret shared by the server, MCP clients (as a Bearer token) and the extension (baked in at build).
// Running this file writes it into the extension source: `bun run token`.
export const TOKEN_PATH =
	process.env.VITAMINE_TOKEN_FILE ?? join(homedir(), ".vitamine", "token");
const GENERATED = join(import.meta.dir, "..", "extension", "src", "token.gen.ts");

function loadToken() {
	if (process.env.VITAMINE_TOKEN) {
		return process.env.VITAMINE_TOKEN;
	}

	if (existsSync(TOKEN_PATH)) {
		return readFileSync(TOKEN_PATH, "utf8").trim();
	}

	mkdirSync(join(TOKEN_PATH, ".."), { recursive: true, mode: 0o700 });
	const token = randomBytes(32).toString("base64url");
	writeFileSync(TOKEN_PATH, `${token}\n`, { mode: 0o600 });
	return token;
}

export const TOKEN = loadToken();

const same = (a: string, b: string) => {
	const x = Buffer.from(a);
	const y = Buffer.from(b);
	return x.length === y.length && timingSafeEqual(x, y);
};

/** Checks an `Authorization: Bearer <token>` header. */
export function authorized(req: Request) {
	const header = req.headers.get("authorization") ?? "";
	return same(header, `Bearer ${TOKEN}`);
}

/** HMAC proof for the extension handshake; each side signs the other's nonce with its own label. */
export const proof = (label: "ext" | "srv", nonce: string) =>
	createHmac("sha256", TOKEN).update(`${label}:${nonce}`).digest("hex");

export const proofMatches = (label: "ext" | "srv", nonce: string, given: unknown) =>
	typeof given === "string" && same(given, proof(label, nonce));

if (import.meta.main) {
	writeFileSync(
		GENERATED,
		`// Generated by server/token.ts from ${TOKEN_PATH}. Do not commit.\nexport default ${JSON.stringify(TOKEN)};\n`,
		{ mode: 0o600 },
	);
	chmodSync(GENERATED, 0o600);
	console.log(`Token from ${TOKEN_PATH} written to extension/src/token.gen.ts`);
}
